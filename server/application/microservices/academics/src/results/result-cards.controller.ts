/**
 * ResultCards Controller — Sprint A.4.4 + A.4.5
 *
 * Endpoints under /academics/result-cards:
 *   GET    /academics/result-cards/:cardId                   — get single (requires enrollmentId query)
 *   GET    /academics/result-cards                           — list (filter by schoolId|examId|enrollmentId)
 *   PATCH  /academics/result-cards/:cardId/conduct           — operator conduct
 *   PATCH  /academics/result-cards/:cardId/remark            — class-teacher remark
 *   PATCH  /academics/result-cards/:cardId/publish           — state-machine publish (terminal)
 *
 * All routes require JWT + permission guard. ResultCard rows are
 * generated by the result-batch Lambda (A.4.3); this controller is
 * operator-facing read + edit + publish only.
 *
 * Invariant 3: `enrollmentId` is the key — it's a required query
 * parameter on every single-card endpoint so we can do an efficient
 * GetItem without a scan.
 *
 * @see docs/pilot-greenlight/a4-sprint-plan.md §3 Phase 2 + §4 A.4.4 + A.4.5
 */

import {
  Controller,
  Get,
  Patch,
  Body,
  Param,
  Query,
  UseGuards,
  Req,
  Logger,
  BadRequestException,
} from '@nestjs/common';
import { Request } from 'express';
import { ResultCardsService } from './result-cards.service';
import { JwtAuthGuard } from '@app/auth/jwt-auth.guard';
import { TenantCredentials, TenantContext, RequirePermission } from '@app/auth';
import { PermissionGuard } from '../common/guards/permission.guard';
import type { ResultCardResponseDto } from '@aibrains/shared-types';
import {
  UpdateResultCardConductDtoZ,
  UpdateResultCardRemarkDtoZ,
  ResultCardPublishDtoZ,
} from '../common/dto/zod-dtos';
import { RequestContext } from '../common/entities';

interface ResultCardListResponseDto {
  items: ResultCardResponseDto[];
  lastEvaluatedKey?: string;
  hasMore: boolean;
}

@Controller('academics/result-cards')
@UseGuards(JwtAuthGuard)
export class ResultCardsController {
  private readonly logger = new Logger(ResultCardsController.name);

  constructor(private readonly resultCardsService: ResultCardsService) {}

  // ==========================================================================
  // GET single
  // ==========================================================================

  @Get(':cardId')
  @UseGuards(PermissionGuard)
  @RequirePermission({ resource: 'result-cards', action: 'view' })
  async getResultCard(
    @Param('cardId') cardId: string,
    @Query('enrollmentId') enrollmentId: string,
    @TenantCredentials() tenant: TenantContext,
    @Req() req: Request,
  ): Promise<ResultCardResponseDto> {
    if (!enrollmentId) {
      throw new BadRequestException({
        errorCode: 'ENROLLMENT_ID_REQUIRED',
        message: 'enrollmentId query parameter is required (entity is keyed by enrollmentId)',
      });
    }
    this.logger.log(`GET /academics/result-cards/${cardId}?enrollmentId=${enrollmentId}`);
    return this.resultCardsService.getResultCard(
      cardId,
      enrollmentId,
      this.buildContext(tenant, req),
    );
  }

  // ==========================================================================
  // GET list
  // ==========================================================================

  @Get()
  @UseGuards(PermissionGuard)
  @RequirePermission({ resource: 'result-cards', action: 'view' })
  async listResultCards(
    @Query('schoolId') schoolId: string,
    @Query('examId') examId: string,
    @Query('termId') termId: string,
    @Query('academicYearId') academicYearId: string,
    @Query('enrollmentId') enrollmentId: string,
    @Query('studentId') studentId: string,
    @Query('status') status: string,
    @Query('isTerminalExam') isTerminalExam: string,
    @Query('isActive') isActive: string,
    @Query('limit') limit: string,
    @Query('cursor') cursor: string,
    @TenantCredentials() tenant: TenantContext,
    @Req() req: Request,
  ): Promise<ResultCardListResponseDto> {
    this.logger.log(
      `GET /academics/result-cards schoolId=${schoolId || '-'} examId=${examId || '-'} enrollmentId=${enrollmentId || '-'}`,
    );
    const parsedLimit = limit ? Math.max(1, Math.min(100, parseInt(limit, 10))) : 50;
    return this.resultCardsService.listResultCards(
      {
        schoolId: schoolId || undefined,
        examId: examId || undefined,
        termId: termId || undefined,
        academicYearId: academicYearId || undefined,
        enrollmentId: enrollmentId || undefined,
        studentId: studentId || undefined,
        status: (status as any) || undefined,
        isTerminalExam:
          isTerminalExam === undefined || isTerminalExam === ''
            ? undefined
            : isTerminalExam === 'true',
        isActive:
          isActive === undefined || isActive === ''
            ? undefined
            : isActive === 'true',
      },
      this.buildContext(tenant, req),
      parsedLimit,
      cursor || undefined,
    );
  }

  // ==========================================================================
  // PATCH conduct (A.4.4)
  // ==========================================================================

  @Patch(':cardId/conduct')
  @UseGuards(PermissionGuard)
  @RequirePermission({ resource: 'result-cards', action: 'update' })
  async updateConduct(
    @Param('cardId') cardId: string,
    @Query('enrollmentId') enrollmentId: string,
    @Body() dto: UpdateResultCardConductDtoZ,
    @TenantCredentials() tenant: TenantContext,
    @Req() req: Request,
  ): Promise<ResultCardResponseDto> {
    if (!enrollmentId) {
      throw new BadRequestException({
        errorCode: 'ENROLLMENT_ID_REQUIRED',
        message: 'enrollmentId query parameter is required',
      });
    }
    this.logger.log(`PATCH /academics/result-cards/${cardId}/conduct`);
    return this.resultCardsService.updateConduct(
      cardId,
      enrollmentId,
      dto,
      this.buildContext(tenant, req),
    );
  }

  // ==========================================================================
  // PATCH remark (A.4.4)
  // ==========================================================================

  @Patch(':cardId/remark')
  @UseGuards(PermissionGuard)
  @RequirePermission({ resource: 'result-cards', action: 'update' })
  async updateRemark(
    @Param('cardId') cardId: string,
    @Query('enrollmentId') enrollmentId: string,
    @Body() dto: UpdateResultCardRemarkDtoZ,
    @TenantCredentials() tenant: TenantContext,
    @Req() req: Request,
  ): Promise<ResultCardResponseDto> {
    if (!enrollmentId) {
      throw new BadRequestException({
        errorCode: 'ENROLLMENT_ID_REQUIRED',
        message: 'enrollmentId query parameter is required',
      });
    }
    this.logger.log(`PATCH /academics/result-cards/${cardId}/remark`);
    return this.resultCardsService.updateRemark(
      cardId,
      enrollmentId,
      dto,
      this.buildContext(tenant, req),
    );
  }

  // ==========================================================================
  // PATCH publish (A.4.5 state machine — single irreversible)
  // ==========================================================================

  @Patch(':cardId/publish')
  @UseGuards(PermissionGuard)
  @RequirePermission({ resource: 'result-cards', action: 'publish' })
  async publishResultCard(
    @Param('cardId') cardId: string,
    @Query('enrollmentId') enrollmentId: string,
    @Body() dto: ResultCardPublishDtoZ,
    @TenantCredentials() tenant: TenantContext,
    @Req() req: Request,
  ): Promise<ResultCardResponseDto> {
    if (!enrollmentId) {
      throw new BadRequestException({
        errorCode: 'ENROLLMENT_ID_REQUIRED',
        message: 'enrollmentId query parameter is required',
      });
    }
    this.logger.log(`PATCH /academics/result-cards/${cardId}/publish`);
    return this.resultCardsService.publishResultCard(
      cardId,
      enrollmentId,
      dto,
      this.buildContext(tenant, req),
    );
  }

  // ==========================================================================
  // Helpers
  // ==========================================================================

  private buildContext(tenant: TenantContext, req: Request): RequestContext {
    return {
      userId: tenant.userId,
      tenantId: tenant.tenantId,
      email: tenant.email,
      role: tenant.globalRole,
      jwtToken: (req.headers.authorization || '').replace(/^Bearer\s+/i, ''),
    };
  }
}
